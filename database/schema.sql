-- =========================
-- USERS / ADMINISTRATORS
-- =========================
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'staff'
        CHECK (role IN ('admin', 'staff')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================
-- PRODUCT CATEGORIES
-- =========================
CREATE TABLE IF NOT EXISTS categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================
-- PRODUCTS
-- =========================
CREATE TABLE IF NOT EXISTS products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NULL,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    specifications TEXT,
    image VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id)
        REFERENCES categories(id)
        ON DELETE SET NULL
        ON UPDATE CASCADE
);

-- =========================
-- SERVICES
-- =========================
CREATE TABLE IF NOT EXISTS services (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    image VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================
-- CUSTOMERS
-- =========================
CREATE TABLE IF NOT EXISTS customers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_name VARCHAR(200),
    contact_person VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(50),
    address TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================
-- GENERAL INQUIRIES
-- =========================
CREATE TABLE IF NOT EXISTS inquiries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NULL,
    subject VARCHAR(255),
    message TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'new'
        CHECK (status IN ('new', 'read', 'replied', 'closed')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_inquiries_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(id)
        ON DELETE SET NULL
        ON UPDATE CASCADE
);

-- =========================
-- QUOTATION REQUESTS
-- =========================
CREATE TABLE IF NOT EXISTS quotation_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NULL,
    product_service VARCHAR(255) NOT NULL,
    quantity VARCHAR(100),
    delivery_location VARCHAR(255),
    tender_lpo_reference VARCHAR(255),
    requirement_type VARCHAR(30) NOT NULL DEFAULT 'Quotation'
        CHECK (
            requirement_type IN (
                'General Inquiry', 'Quotation', 'Tender', 'LPO'
            )
        ),
    required_delivery_date DATE,
    additional_requirements TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'new'
        CHECK (
            status IN (
                'new', 'reviewing', 'quoted', 'completed', 'cancelled'
            )
        ),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_quotation_requests_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(id)
        ON DELETE SET NULL
);

-- =========================
-- TENDER REQUESTS
-- =========================
CREATE TABLE IF NOT EXISTS tender_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NULL,
    tender_reference VARCHAR(150),
    tender_title VARCHAR(255) NOT NULL,
    description TEXT,
    submission_deadline DATE,
    delivery_location VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'received'
        CHECK (
            status IN (
                'received', 'under_review', 'sourcing', 'submitted',
                'awarded', 'completed', 'unsuccessful'
            )
        ),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_tender_requests_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(id)
        ON DELETE SET NULL
        ON UPDATE CASCADE
);

-- =========================
-- QUOTATION / TENDER DOCUMENTS
-- =========================
CREATE TABLE IF NOT EXISTS quotation_documents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_request_id INTEGER NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_path VARCHAR(500) NOT NULL,
    file_type VARCHAR(100),
    file_size INTEGER,
    uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_quotation_documents_request
        FOREIGN KEY (quotation_request_id)
        REFERENCES quotation_requests(id)
        ON DELETE CASCADE
);

-- =========================
-- SUPPLIERS
-- =========================
CREATE TABLE IF NOT EXISTS suppliers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(200) NOT NULL,
    contact_person VARCHAR(150),
    email VARCHAR(150),
    phone VARCHAR(50),
    address TEXT,
    products_services TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================
-- INDEXES FOR FOREIGN KEYS
-- AND COMMON LOOKUPS
-- =========================
CREATE INDEX IF NOT EXISTS idx_products_category_id
    ON products(category_id);

CREATE INDEX IF NOT EXISTS idx_quotation_requests_customer_id
    ON quotation_requests(customer_id);

CREATE INDEX IF NOT EXISTS idx_tender_requests_customer_id
    ON tender_requests(customer_id);

CREATE INDEX IF NOT EXISTS idx_quotation_documents_request_id
    ON quotation_documents(quotation_request_id);

CREATE INDEX IF NOT EXISTS idx_inquiries_status
    ON inquiries(status);

CREATE INDEX IF NOT EXISTS idx_quotation_requests_status
    ON quotation_requests(status);

CREATE INDEX IF NOT EXISTS idx_tender_requests_status
    ON tender_requests(status);
